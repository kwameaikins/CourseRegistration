// Host-level redirect rules for next.config.ts (Coding Docs/20 Phase 2).
//
// Plain ESM rather than TypeScript because next.config.ts is transpiled on
// its own and cannot pull in sibling .ts modules; vitest imports this file
// directly for tests/unit/host-redirects.test.ts.
//
// Two modes, chosen by CANONICAL_HOST:
//
//   unset  → the pre-cutover world. The only host rule is the emergency
//            stopgap of 2026-09-03 (knowsia.com → reg.knowsia.com, TEMPORARY
//            307) for the day the WordPress VPS is down again.
//   set    → the post-cutover world. Every legacy host (www., reg., anything
//            passed in extraLegacyHosts) 308s to the canonical host, path
//            preserved, and the emergency rule is gone — it would otherwise
//            loop against these.
//
// The value is sanitised the same way KNOWSIA_APP_FRONTEND_URL is: a stray CR
// from a Windows pipe once took the production build down with "Invalid
// redirects found" (2026-08-23). A malformed host degrades to "unset", never
// to a failed deploy.

const HOST_PATTERN = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/i;

/** Lower-cased, whitespace-stripped host, or null if it is not a bare host. */
export function sanitizeHost(value) {
  const host = String(value ?? '')
    .replace(/\s+/g, '')
    .replace(/^https?:\/\//i, '')
    .replace(/\/.*$/, '')
    .toLowerCase();
  return HOST_PATTERN.test(host) ? host : null;
}

function escapeForHasValue(host) {
  return host.replace(/\./g, '\\.');
}

/**
 * @param {object} opts
 * @param {string | null} opts.canonicalHost  e.g. "knowsia.com"; null = pre-cutover
 * @param {string[]} [opts.extraLegacyHosts]  hosts besides www./reg. that must 308 to canonical
 * @returns {Array<{source: string, has: Array<{type: 'host', value: string}>, destination: string, permanent: boolean}>}
 */
export function buildHostRedirects({ canonicalHost, extraLegacyHosts = [] }) {
  if (!canonicalHost) {
    return [
      {
        source: '/:path*',
        has: [{ type: 'host', value: '(www\\.)?knowsia\\.com' }],
        destination: 'https://reg.knowsia.com/:path*',
        permanent: false,
      },
    ];
  }

  const legacyHosts = [`www.${canonicalHost}`, `reg.${canonicalHost}`, ...extraLegacyHosts]
    .map(sanitizeHost)
    .filter((host, index, all) => host && host !== canonicalHost && all.indexOf(host) === index);

  return legacyHosts.map((host) => ({
    source: '/:path*',
    has: [{ type: 'host', value: escapeForHasValue(host) }],
    destination: `https://${canonicalHost}/:path*`,
    permanent: true,
  }));
}

/**
 * The WordPress-era path map, generated by scripts/seo/build-legacy-redirects.mjs
 * into config/legacy-redirects.json. Only applied once CANONICAL_HOST is set —
 * those paths only ever existed on knowsia.com, and nothing may change on
 * reg.knowsia.com before the flip.
 *
 * @param {Array<{source: string, destination: string}>} entries
 */
export function toNextRedirects(entries) {
  return entries
    .filter((entry) => entry && typeof entry.source === 'string' && typeof entry.destination === 'string')
    .filter((entry) => entry.source.startsWith('/') && entry.source !== entry.destination)
    .map((entry) => ({ source: entry.source, destination: entry.destination, permanent: true }));
}
